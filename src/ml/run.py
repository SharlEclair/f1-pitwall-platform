"""One command: evaluate, log to MLflow (local file store) and regenerate docs/ML-RESULTS.md.

Usage: python -m ml.run data/ml/laps_clean.parquet docs/ML-RESULTS.md
Every number in the results page comes from this run; nothing is typed in by hand.
"""

import hashlib
import json
import sys
from pathlib import Path

import mlflow
import polars as pl

from ml.lapmodel import (
    GBM_FEATURES,
    GBM_PARAMS,
    MIN_TARGETS,
    N_CAL,
    bootstrap_ci,
    build_examples,
    estimate_effects,
    fit_gbm,
    run_loro,
)

METHODS = {"b0": "B0 persistence", "b1": "B1 linear physics", "gbm": "LightGBM"}
HORIZONS = [(0, 10, "0-9"), (10, 20, "10-19"), (20, 40, "20-39"), (40, 1000, "40+")]
ASSUMED_FUEL_EFFECT = -0.04  # s per lap, the dbt assumption (faster each lap)


def verdict(difference, name_a, name_b):
    """Plain-language reading of a paired difference (a minus b) with its (mean, low, high) CI."""
    mean, low, high = difference
    interval = f"mean {mean:+.3f} s, 95% interval {low:+.3f} to {high:+.3f}"
    if high < 0:
        return f"{name_a} beats {name_b}: {interval}."
    if low > 0:
        return f"{name_b} beats {name_a}: {interval}."
    return f"No detectable difference between {name_a} and {name_b}: {interval} includes zero."


def summarise(examples, folds, predictions):
    out = {"n_races": folds.height, "n_laps": predictions.height,
           "n_driver_races": examples.select("session_key", "driver_number").unique().height}
    out["race_mae"] = {m: bootstrap_ci(folds[f"mae_{m}"].to_list()) for m in METHODS}
    out["lap_mae"] = {
        m: float((predictions[f"pred_{m}"] - predictions["actual"]).abs().mean()) for m in METHODS
    }
    for a, b in (("gbm", "b1"), ("gbm", "b0"), ("b1", "b0")):
        diffs = (folds[f"mae_{a}"] - folds[f"mae_{b}"]).to_list()
        out[f"diff_{a}_{b}"] = bootstrap_ci(diffs)
        out[f"races_{a}_better_than_{b}"] = int(sum(d < 0 for d in diffs))
    err = predictions.with_columns(
        *[(pl.col(f"pred_{m}") - pl.col("actual")).abs().alias(f"err_{m}") for m in METHODS]
    )
    out["by_compound"] = (
        err.group_by("compound").agg(pl.len().alias("n"),
                                     *[pl.col(f"err_{m}").mean() for m in METHODS])
        .sort("compound").rows(named=True)
    )
    horizon = pl.when(False).then(None)
    for low, high, label in HORIZONS:
        horizon = horizon.when((pl.col("lap_diff") >= low) & (pl.col("lap_diff") < high)).then(
            pl.lit(label))
    out["by_horizon"] = (
        err.with_columns(horizon.alias("horizon"))
        .group_by("horizon").agg(pl.len().alias("n"), *[pl.col(f"err_{m}").mean() for m in METHODS])
        .sort(pl.col("horizon").replace_strict({h[2]: h[0] for h in HORIZONS}))
        .rows(named=True)
    )
    out["folds"] = folds.sort("mae_gbm").rows(named=True)
    return out


def render(results, effects, data_hash):
    r = results
    lines = [
        "# Lap-time model results (generated)",
        "",
        "Generated by `python -m ml.run`; do not edit by hand. "
        "All numbers come from one logged run.",
        "",
        "## Task and evaluation",
        "",
        "Predict a driver's later clean-lap times in a held-out race. For each held-out race every "
        f"method may use each driver's first {N_CAL} clean laps (the calibration window) and "
        "nothing else from that race, so the baselines and the model get the same information "
        "about it. "
        "The model is trained on the other races only (leave-one-race-out); the baselines' "
        "coefficients likewise come from the training races. Dry races only; sprints, wet races "
        "and laps flagged by the data-quality layer are excluded.",
        "",
        f"- Held-out races: {r['n_races']}; driver-race calibrations: {r['n_driver_races']}; "
        f"predicted laps: {r['n_laps']}.",
        f"- Choices fixed before any result was seen: calibration window {N_CAL} laps, minimum "
        f"{MIN_TARGETS} later laps per driver, LightGBM hyperparameters (below), 2,000 bootstrap "
        "resamples over races, 95% percentile intervals. No hyperparameter search was run.",
        f"- Data file SHA-256: `{data_hash[:16]}...`; LightGBM parameters: `{GBM_PARAMS}`.",
        "",
        "## Mean absolute error (seconds, lower is better)",
        "",
        "| Method | Mean across races (95% CI over races) | Over all laps |",
        "|---|---|---|",
    ]
    for m, label in METHODS.items():
        mean, low, high = r["race_mae"][m]
        lines.append(f"| {label} | {mean:.3f} ({low:.3f} to {high:.3f}) | {r['lap_mae'][m]:.3f} |")
    lines += ["", "## Paired differences between methods (per race, 95% CI over races)", ""]
    for a, b in (("gbm", "b1"), ("gbm", "b0"), ("b1", "b0")):
        lines.append(f"- {verdict(r[f'diff_{a}_{b}'], METHODS[a], METHODS[b])} "
                     f"{METHODS[a]} was better in {r[f'races_{a}_better_than_{b}']} of "
                     f"{r['n_races']} races.")
    lines += ["", "## Where each method fails", "", "By compound (all held-out laps):", "",
              "| Compound | Laps | B0 | B1 | LightGBM |", "|---|---|---|---|---|"]
    for row in r["by_compound"]:
        lines.append(f"| {row['compound']} | {row['n']} | {row['err_b0']:.3f} | "
                     f"{row['err_b1']:.3f} | {row['err_gbm']:.3f} |")
    lines += ["", "By laps since the calibration window:", "",
              "| Laps ahead | Laps | B0 | B1 | LightGBM |", "|---|---|---|---|---|"]
    for row in r["by_horizon"]:
        lines.append(f"| {row['horizon']} | {row['n']} | {row['err_b0']:.3f} | "
                     f"{row['err_b1']:.3f} | {row['err_gbm']:.3f} |")
    lines += ["", "By race (sorted by LightGBM error):", "",
              "| Race | Laps | B0 | B1 | LightGBM |", "|---|---|---|---|---|"]
    for row in r["folds"]:
        lines.append(f"| {row['circuit_short_name']} | {row['n_laps']} | {row['mae_b0']:.3f} | "
                     f"{row['mae_b1']:.3f} | {row['mae_gbm']:.3f} |")
    slope = effects["lap_slope"]
    lines += [
        "", "## Lap-number effect estimated from the data (replaces the assumed fuel effect)", "",
        "B1's lap-number coefficient is the change in lap time per lap of race progress after "
        "removing tyre age and compound. It is fuel burn plus track evolution plus anything else "
        "that changes with race progress, so it is not a pure fuel estimate. Intervals come from "
        "resampling races (500 draws).", "",
        f"- Lap-number effect: {slope[0]:+.4f} s per lap "
        f"(95% CI {slope[1]:+.4f} to {slope[2]:+.4f}); the dbt assumption is "
        f"{ASSUMED_FUEL_EFFECT:+.2f}.",
    ]
    for c in ("SOFT", "MEDIUM", "HARD"):
        s = effects[f"age_slope_{c}"]
        lines.append(f"- Tyre-age slope {c}: {s[0]:+.4f} s per lap of age "
                     f"(95% CI {s[1]:+.4f} to {s[2]:+.4f}).")
    lines += [
        "", "## Limitations", "",
        "- One season (2024); races are not independent draws and each circuit appears once, so "
        "the model never sees the held-out circuit.",
        f"- The first {N_CAL} clean laps of a driver in a race are required, so drivers who retire "
        "early or never have enough clean laps are not scored.",
        "- Lap-number and tyre-age effects are only separately identified through differences "
        "between stints (stint starts and compound changes).",
        "- Hyperparameters were fixed, not tuned; a tuned model could do better or worse.", "",
    ]
    return "\n".join(lines)


def main(data_path, out_path):
    data_bytes = Path(data_path).read_bytes()
    data_hash = hashlib.sha256(data_bytes).hexdigest()
    laps = pl.read_parquet(data_path)
    examples = build_examples(laps)
    folds, predictions = run_loro(examples)
    results = summarise(examples, folds, predictions)
    effects = estimate_effects(examples)
    text = render(results, effects, data_hash)
    Path(out_path).write_text(text, encoding="utf-8")
    app_dir = Path("dashboard/data")
    app_dir.mkdir(parents=True, exist_ok=True)
    (app_dir / "ml_results.json").write_text(
        json.dumps({"results": results, "effects": effects, "assumed_fuel_effect":
                    ASSUMED_FUEL_EFFECT}, indent=1), encoding="utf-8")

    mlflow.set_tracking_uri("sqlite:///mlflow.db")
    mlflow.set_experiment("f1-lap-time")
    with mlflow.start_run(run_name="loro-calibration-window"):
        mlflow.log_params({
            "n_cal": N_CAL, "min_targets": MIN_TARGETS, "features": ",".join(GBM_FEATURES),
            "data_sha256": data_hash, "n_races": results["n_races"], "n_laps": results["n_laps"],
            **{f"gbm_{k}": v for k, v in GBM_PARAMS.items()},
        })
        for m in METHODS:
            mean, low, high = results["race_mae"][m]
            mlflow.log_metrics({f"mae_mean_{m}": mean, f"mae_ci_low_{m}": low,
                                f"mae_ci_high_{m}": high, f"mae_laps_{m}": results["lap_mae"][m]})
        for step, row in enumerate(folds.sort("session_key").rows(named=True)):
            mlflow.log_metrics({f"fold_mae_{m}": row[f"mae_{m}"] for m in METHODS}, step=step)
        for a, b in (("gbm", "b1"), ("gbm", "b0"), ("b1", "b0")):
            mean, low, high = results[f"diff_{a}_{b}"]
            mlflow.log_metrics({f"diff_{a}_minus_{b}": mean, f"diff_{a}_minus_{b}_ci_low": low,
                                f"diff_{a}_minus_{b}_ci_high": high})
        mlflow.log_metric("lap_number_effect", effects["lap_slope"][0])
        folds.write_csv("folds.csv")
        importance = fit_gbm(examples).booster_.feature_importance(importance_type="gain")
        pl.DataFrame({"feature": GBM_FEATURES, "gain": importance}).sort(
            "gain", descending=True).write_csv("feature_importance.csv")
        for artifact in ("folds.csv", "feature_importance.csv", out_path):
            mlflow.log_artifact(artifact)
    Path("folds.csv").unlink()
    Path("feature_importance.csv").unlink()
    return results, effects


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
    print(f"wrote {sys.argv[2]}")
