"""Regenerate docs/SEASON-RESULTS.md: degradation and pit loss per season and pooled.

Usage: python -m ml.season_report data/export/marts docs/SEASON-RESULTS.md
Inputs are the Parquet marts written by `python -m snowload.export_marts`; every number in the page
comes from them. Method as in Phase 1: the median across races of each race's own estimate.
"""

import sys
from pathlib import Path

import polars as pl

COMPOUNDS = ("SOFT", "MEDIUM", "HARD")


def degradation_table(deg):
    deg = deg.filter(pl.col("compound").is_in(COMPOUNDS) & pl.col("slope_s_per_lap").is_not_null())
    by = lambda frame: frame.group_by("compound").agg(  # noqa: E731
        pl.col("slope_s_per_lap").median().alias("corrected"),
        pl.col("slope_uncorrected").median().alias("uncorrected"),
        pl.len().alias("n_fits"),
    )
    rows = []
    for season in sorted(deg["season"].unique().to_list()):
        rows += [(str(season), r) for r in by(deg.filter(pl.col("season") == season)).to_dicts()]
    rows += [("all", r) for r in by(deg).to_dicts()]
    return rows


def pit_table(pit):
    pit = pit.filter(pl.col("median_pit_loss_s").is_not_null())
    agg = lambda frame: frame.group_by("track_status").agg(  # noqa: E731
        pl.col("median_pit_loss_s").median().alias("loss"),
        pl.col("n_stops_with_loss").sum().alias("stops"),
        pl.len().alias("races"),
    )
    rows = []
    for season in sorted(pit["season"].unique().to_list()):
        rows += [(str(season), r) for r in agg(pit.filter(pl.col("season") == season)).to_dicts()]
    rows += [("all", r) for r in agg(pit).to_dicts()]
    return rows


def render(deg, pit, stint_check_note):
    lines = [
        "# Results by season (generated)", "",
        "Generated by `python -m ml.season_report`; do not edit by hand. Each figure is the median "
        "across races of that race's own estimate, as in the first season's report. Sessions whose "
        "stints disagree with their pit stops are left out of clean laps (see ADR 0017).", "",
        "## Tyre degradation (within-stint slope, assumed fuel effect 0.04 s/lap)", "",
        "| Season | Compound | Median slope, fuel-corrected (s/lap) | Median slope, uncorrected "
        "(s/lap) | Race fits |", "|---|---|---|---|---|",
    ]
    for season, r in degradation_table(deg):
        lines.append(f"| {season} | {r['compound']} | {r['corrected']:+.3f} | "
                     f"{r['uncorrected']:+.3f} | {r['n_fits']} |")
    lines += ["", "## Pit-stop loss (in-lap + out-lap minus two reference laps)", "",
              "| Season | Track status | Median of race medians (s) | Stops | Races |",
              "|---|---|---|---|---|"]
    order = {"GREEN": 0, "SC": 1, "VSC": 2}
    ranked = sorted(pit_table(pit), key=lambda x: (x[0], order.get(x[1]["track_status"], 9)))
    for season, r in ranked:
        lines.append(f"| {season} | {r['track_status']} | {r['loss']:.1f} | {r['stops']} | "
                     f"{r['races']} |")
    stop = pit.filter(pl.col("n_stops_with_stationary_time") > 0)
    lines += ["", "## Stationary time (`stop_duration`) coverage", "",
              "| Season | Stops with stationary time | Stops | Median stationary time (s) |",
              "|---|---|---|---|"]
    for season in sorted(pit["season"].unique().to_list()):
        s = pit.filter(pl.col("season") == season)
        have = s["n_stops_with_stationary_time"].sum()
        med = stop.filter(pl.col("season") == season)["median_stop_duration_s"].median()
        shown = f"{med:.2f}" if med is not None else "n/a"
        lines.append(f"| {season} | {have} | {s['n_stops'].sum()} | {shown} |")
    lines += ["", stint_check_note, ""]
    return "\n".join(lines)


def main(marts_dir, out_path):
    marts = Path(marts_dir)
    deg = pl.read_parquet(marts / "mart_tyre_degradation.parquet")
    pit = pl.read_parquet(marts / "mart_pit_loss.parquet")
    note = ("Stop counts in the stationary-time table are stops in races with a pit-loss row "
            "(stops over 60 s excluded); the stationary-time median is a median of per-race "
            "medians.")
    Path(out_path).write_text(render(deg, pit, note), encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:3])
    print(f"wrote {sys.argv[2]}")
