"""Regenerate docs/UNDERCUT-RESULTS.md and dashboard/data/undercut_results.json (ADR 0016).

Usage: python -m undercut.report data/export/marts docs/UNDERCUT-RESULTS.md
Reads the exported marts (`python -m snowload.export_marts`). Every number comes from them: the
counts and Wilson intervals from mart_undercut_summary, and a bootstrap over races (attempts in one
race are not independent) from mart_undercut_events using the primary definition's thresholds.
"""

import json
import sys
from pathlib import Path

import numpy as np
import polars as pl

N_BOOT = 2000
SEED = 0


def primary_attempts(events, gap_s, window, exclude_neutralised):
    keep = (
        pl.col("gap_s").is_not_null() & (pl.col("gap_s") <= gap_s)
        & pl.col("response_laps").is_between(1, window)
        & ~pl.col("b_stopped_same_or_previous_lap")
    )
    if exclude_neutralised:
        keep = keep & ~pl.col("neutralised_in_window")
    return events.filter(keep)


def bootstrap_rate(attempts, n_boot=N_BOOT, seed=SEED):
    """Pooled success rate when resampling races (sessions) with replacement; 95% percentile CI."""
    decided = attempts.filter(pl.col("outcome").is_in(["success", "failure"]))
    per_race = decided.group_by("session_key").agg(
        (pl.col("outcome") == "success").sum().alias("s"), pl.len().alias("n")
    )
    wins, totals = per_race["s"].to_numpy(), per_race["n"].to_numpy()
    rng = np.random.default_rng(seed)
    draws = rng.integers(0, len(wins), size=(n_boot, len(wins)))
    rates = wins[draws].sum(axis=1) / totals[draws].sum(axis=1)
    low, high = np.quantile(rates, [0.025, 0.975])
    return float(wins.sum() / totals.sum()), float(low), float(high), int(len(wins))


def cell(row):
    if row is None or row["n_decided"] == 0:
        return "n/a"
    return f"{100 * row['success_rate']:.0f}% (n={row['n_decided']})"


def grid_table(summary, exclude):
    sub = summary.filter(
        (pl.col("season_scope") == "all") & (pl.col("exclude_neutralised") == exclude)
    )
    windows = sorted(sub["response_window_laps"].unique().to_list())
    heads = " | ".join(f"window {w} lap{'s' if w > 1 else ''}" for w in windows)
    lines = [f"| Gap threshold | {heads} |", "|---|" + "---|" * len(windows)]
    for gap in sorted(sub["gap_threshold_s"].unique().to_list()):
        cells = []
        for w in windows:
            match = sub.filter(
                (pl.col("gap_threshold_s") == gap) & (pl.col("response_window_laps") == w)
            )
            cells.append(cell(match.row(0, named=True) if match.height else None))
        lines.append(f"| {gap:g} s | " + " | ".join(cells) + " |")
    return lines


def build(summary, events):
    primary = summary.filter(pl.col("is_primary"))
    gap, window = primary["gap_threshold_s"][0], int(primary["response_window_laps"][0])
    attempts = primary_attempts(events, gap, window, True)
    rate, low, high, n_races = bootstrap_rate(attempts)
    return {
        "primary": {"gap_threshold_s": gap, "response_window_laps": window},
        "by_scope": primary.sort("season_scope").select(
            "season_scope", "n_attempts", "n_success", "n_failure", "n_inconclusive",
            "n_sessions", "success_rate", "wilson_low", "wilson_high").rows(named=True),
        "bootstrap_over_races": {"rate": rate, "low": low, "high": high, "n_races": n_races,
                                 "n_boot": N_BOOT},
        "grid": summary.filter(pl.col("season_scope") == "all").sort("grid_id").rows(named=True),
        "monza_attempts": attempts.filter(pl.col("circuit_short_name") == "Monza").height,
    }


def reading(result, summary):
    """One sentence from the grid itself: how far the rate moves with the gap threshold."""
    window = result["primary"]["response_window_laps"]
    sub = summary.filter(
        (pl.col("season_scope") == "all") & pl.col("exclude_neutralised")
        & (pl.col("response_window_laps") == window)
    ).sort("gap_threshold_s")
    first, last = sub.row(0, named=True), sub.row(sub.height - 1, named=True)
    return (
        f"How to read it: with a {window}-lap window the rate runs from "
        f"{100 * first['success_rate']:.0f}% (gap up to {first['gap_threshold_s']:g} s, "
        f"n={first['n_decided']}) to {100 * last['success_rate']:.0f}% (gap up to "
        f"{last['gap_threshold_s']:g} s, n={last['n_decided']}). The starting gap moves the answer "
        "far more than the other choices, so the primary cell is one point on a curve, not a "
        "stand-alone number. Cells with small n have wide intervals."
    )


def render(result, summary):
    p = result["primary"]
    boot = result["bootstrap_over_races"]
    lines = [
        "# Undercut results (generated)", "",
        "Generated by `python -m undercut.report`; do not edit by hand. The definition was "
        "frozen in [ADR 0016](adr/0016-undercut-definition.md) before any outcome was computed. "
        "This is the frequency of success **under that definition**, not \"the\" undercut rate.",
        "",
        "## Primary definition", "",
        f"Car A stops on lap L with car B directly ahead and a known gap of at most "
        f"{p['gap_threshold_s']:g} s; B stops on one of the next {p['response_window_laps']} laps "
        "(not on the same or previous lap); no Safety Car, VSC or red-flag lap in the window. "
        "Success: A is ahead of B at the start of B's lap two laps after B's stop. "
        "Inconclusive attempts (a car has no lap or position there) are counted but not in the "
        "rate.",
        "", "## Result", "",
        "| Scope | Attempts | Success | Failure | Inconclusive | Races | Rate | 95% Wilson |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in result["by_scope"]:
        rate = "n/a" if r["success_rate"] is None else f"{100 * r['success_rate']:.1f}%"
        interval = ("n/a" if r["wilson_low"] is None
                    else f"{100 * r['wilson_low']:.1f}% to {100 * r['wilson_high']:.1f}%")
        lines.append(f"| {r['season_scope']} | {r['n_attempts']} | {r['n_success']} | "
                     f"{r['n_failure']} | {r['n_inconclusive']} | {r['n_sessions']} | {rate} | "
                     f"{interval} |")
    lines += [
        "", f"Pooled, bootstrapping the {boot['n_races']} races that contribute decided attempts "
        f"({boot['n_boot']:,} resamples): {100 * boot['rate']:.1f}% "
        f"(95% interval {100 * boot['low']:.1f}% to {100 * boot['high']:.1f}%). "
        "Attempts in one race are not independent, so this interval is the one to trust over the "
        "Wilson interval.", "",
        "## Sensitivity (pooled, success rate and number of decided attempts)", "",
        "Neutralised windows excluded (the primary treatment):", "",
        *grid_table(summary, True), "",
        "Neutralised windows included:", "",
        *grid_table(summary, False), "",
        reading(result, summary), "",
        "## Context, not validation", "",
        "An earlier, separate simulator gave 53.77% as a model probability that one hypothetical "
        "Monza stop would beat one named rival, and called it too close to call. That is a model "
        "estimate for a single stop; this page counts what happened across many stops. The two are "
        "different quantities, so neither validates the other. "
        f"Monza itself contributes {result['monza_attempts']} attempts under the primary "
        "definition across the three seasons, too few to say anything about Monza specifically.",
        "", "## What the rate does not control", "",
        "- Pace difference between the two cars: a faster car passes anyway.",
        "- Tyre compound and age of both cars, out-lap traffic, DRS and overtaking difficulty by "
        "circuit, team stop speed (stationary time is missing for 2023 and most of 2024), and "
        "positions gained or lost to cars other than B.",
        "- Position is the on-track order from the position stream, not the official "
        "classification.",
        "- Attempts are a small sample: more seasons are the only honest way to tighten the "
        "intervals.", "",
    ]
    return "\n".join(lines)


def main(marts_dir, out_path):
    marts = Path(marts_dir)
    summary = pl.read_parquet(marts / "mart_undercut_summary.parquet")
    events = pl.read_parquet(marts / "mart_undercut_events.parquet")
    result = build(summary, events)
    Path(out_path).write_text(render(result, summary), encoding="utf-8")
    app = Path("dashboard/data")
    app.mkdir(parents=True, exist_ok=True)
    (app / "undercut_results.json").write_text(json.dumps(result, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:3])
    print(f"wrote {sys.argv[2]}")
